#!/usr/bin/env python3
"""
Write a thin content/observations/YYYY-MM.md for every fetched month in
data/observations/. The table and species list are rendered by
templates/observations_month.html from the month's JSON.

Usage:
    python scripts/make_observation_pages.py
"""

from datetime import date

from common import OBSERVATIONS_CONTENT, OBSERVATIONS_DIR


def main() -> None:
    written = 0
    for path in sorted(OBSERVATIONS_DIR.glob("*.json")):
        month = path.stem                      # "2026-10"
        first = date.fromisoformat(f"{month}-01")
        page = OBSERVATIONS_CONTENT / f"{month}.md"
        page.write_text(
            "+++\n"
            "# Generated by scripts/make_observation_pages.py; content comes from\n"
            f"# data/observations/{month}.json (scripts/fetch_observations.py).\n"
            f'title = "{first:%B %Y}"\n'
            f"date = {first.isoformat()}\n"
            'template = "observations_month.html"\n'
            "\n[extra]\n"
            f'month = "{month}"\n'
            "+++\n",
            encoding="utf-8",
        )
        written += 1
    print(f"Wrote {written} observation pages to {OBSERVATIONS_CONTENT.relative_to(OBSERVATIONS_CONTENT.parents[1])}")


if __name__ == "__main__":
    main()
